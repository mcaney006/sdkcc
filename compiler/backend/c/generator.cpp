std::vector<GeneratedFile> generate(const nair::Module &module,
                                    const CodegenPlan &plan,
                                    bool include_cpp_target) {
  return {
      {.relative_path = "CMakeLists.txt",
       .content = generate_cmake(plan, include_cpp_target)},
      {.relative_path = std::filesystem::path{"include"} / plan.library /
                        (plan.library + ".h"),
       .content = generate_header(module, plan)},
      {.relative_path = std::filesystem::path{"src"} / (plan.library + ".c"),
       .content = generate_source(module, plan)},
      {.relative_path =
           std::filesystem::path{"cmake"} / (plan.library + "Config.cmake.in"),
       .content = generate_config_in(plan)},
      {.relative_path =
           std::filesystem::path{"cmake"} / (plan.library + ".pc.in"),
       .content = generate_pc_in(plan)},
  };
}

